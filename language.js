  // =======================================================
  // APPLY TEXT
  // =======================================================

  function applyText(
    language
  ) {

    document
      .querySelectorAll(
        "[data-i18n]"
      )
      .forEach(
        element => {

          const key =
            element.dataset.i18n;


          if (
            copy[language][key] !==
            undefined
          ) {

            element.textContent =
              copy[language][key];

          }

        }
      );


    document
      .querySelectorAll(
        "[data-i18n-html]"
      )
      .forEach(
        element => {

          const key =
            element.dataset.i18nHtml;


          if (
            copy[language][key] !==
            undefined
          ) {

            element.innerHTML =
              copy[language][key];

          }

        }
      );


    document
      .querySelectorAll(
        "[data-i18n-aria]"
      )
      .forEach(
        element => {

          const key =
            element.dataset.i18nAria;


          if (
            copy[language][key] !==
            undefined
          ) {

            element.setAttribute(
              "aria-label",
              copy[language][key]
            );

          }

        }
      );

  }


  // =======================================================
  // SET LANGUAGE
  // =======================================================

  function setLanguage(
    language
  ) {

    const selected =
      language === "de"
        ? "de"
        : "en";


    document.documentElement.lang =
      selected;


    applyText(
      selected
    );


    languageButtons.forEach(
      button => {

        const active =
          button.dataset.language ===
          selected;


        button.setAttribute(
          "aria-pressed",
          String(active)
        );

      }
    );


    document.title =
      metadata[selected].title;


    const description =
      document.querySelector(
        'meta[name="description"]'
      );


    if (description) {

      description.content =
        metadata[selected]
          .description;

    }


    try {

      localStorage.setItem(
        "portfolio-language",
        selected
      );

    }

    catch {
      // Ignore storage problems.
    }

  }


  // =======================================================
  // BUTTON EVENTS
  // =======================================================

  languageButtons.forEach(
    button => {

      button.addEventListener(
        "click",
        () => {

          setLanguage(
            button.dataset.language
          );

        }
      );

    }
  );


  // =======================================================
  // LOAD SAVED LANGUAGE
  // =======================================================

  let startingLanguage =
    "en";


  try {

    const saved =
      localStorage.getItem(
        "portfolio-language"
      );


    if (
      saved === "de"
    ) {

      startingLanguage =
        "de";

    }

  }

  catch {

    startingLanguage =
      "en";

  }


  setLanguage(
    startingLanguage
  );


